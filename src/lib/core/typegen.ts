/**
 * TypeScript interface generator — the equivalent of `payload generate:types`.
 * Pure function: CMSConfig in, .ts source out.
 */
import type { CMSConfig, CollectionConfig, Field, GlobalConfig } from './types';

function pascal(slug: string): string {
	return slug
		.replace(/[-_]+/g, ' ')
		.replace(/\b\w/g, (c) => c.toUpperCase())
		.replace(/ /g, '');
}

/** Singularize naively: posts→Post, categories→Category, media→Media. */
function interfaceName(slug: string): string {
	const p = pascal(slug);
	if (/ies$/i.test(p)) return p.replace(/ies$/i, 'y');
	if (/ses$/i.test(p) || /Media$/i.test(p)) return p;
	return p.replace(/s$/i, '');
}

function fieldType(f: Field, relNames: Map<string, string>): string {
	switch (f.type) {
		case 'text':
		case 'textarea':
		case 'html':
		case 'email':
		case 'date':
			return 'string';
		case 'richText':
			return 'import("$lib/core/richtext").RichTextNode[] | string';
		case 'number':
			return 'number';
		case 'checkbox':
			return 'boolean';
		case 'json':
			return 'unknown';
		case 'select': {
			const union = f.options.map((o) => `'${o.value}'`).join(' | ');
			return f.hasMany ? `(${union})[]` : union;
		}
		case 'relationship': {
			const related = relNames.get(f.relationTo) ?? 'string';
			const one = `string | ${related}`;
			return f.hasMany ? `(${one})[]` : one;
		}
		case 'upload': {
			const one = `string | ${relNames.get(f.relationTo) ?? 'string'}`;
			return f.hasMany ? `(${one})[]` : one;
		}
		case 'array': {
			return `{\n${f.fields.map((s) => `\t\t${prop(s, relNames, 2)}`).join('\n')}\n\t}[]`;
		}
		case 'blocks': {
			const variants = f.blocks.map(
				(b) =>
					`{\n\t\tblockType: '${b.slug}';\n${b.fields
						.map((s) => `\t\t${prop(s, relNames, 2)}`)
						.join('\n')}\n\t}`
			);
			return `(${variants.join(' | ')})[]`;
		}
	}
}

function prop(f: Field, relNames: Map<string, string>, _indent = 1): string {
	const optional = f.required ? '' : '?';
	return `${f.name}${optional}: ${fieldType(f, relNames)};`;
}

function docInterface(
	name: string,
	col: Partial<Pick<CollectionConfig, 'auth' | 'versions' | 'upload'>> &
		Pick<CollectionConfig, 'fields'>,
	relNames: Map<string, string>
): string {
	const lines: string[] = [`export interface ${name} {`, '\tid: string;'];
	if (col.auth) lines.push('\temail: string;');
	if ('upload' in col && col.upload)
		lines.push(
			'\tfilename: string;',
			'\tmimeType: string;',
			'\tfilesize: number;',
			'\turl: string;'
		);
	if (col.versions) lines.push(`\t_status?: 'draft' | 'published';`);
	for (const f of col.fields) lines.push(`\t${prop(f, relNames)}`);
	lines.push('\tcreatedAt?: string;');
	lines.push('\tupdatedAt?: string;');
	lines.push('}');
	return lines.join('\n');
}

export function generateTypes(config: CMSConfig): string {
	const relNames = new Map<string, string>();
	for (const col of config.collections) relNames.set(col.slug, interfaceName(col.slug));

	const parts: string[] = [
		'/**',
		' * Generated by highseam (`npm run generate:types`).',
		' * DO NOT EDIT — regenerate after changing src/cms.config.ts.',
		' */',
		''
	];

	for (const col of config.collections) {
		parts.push(docInterface(relNames.get(col.slug)!, col, relNames), '');
	}
	for (const g of config.globals ?? ([] as GlobalConfig[])) {
		parts.push(docInterface(`${pascal(g.slug)}Global`, { fields: g.fields }, relNames), '');
	}

	parts.push(
		'export interface CollectionTypes {',
		...config.collections.map((c) => `\t${c.slug}: ${relNames.get(c.slug)};`),
		'}',
		''
	);
	return parts.join('\n');
}
